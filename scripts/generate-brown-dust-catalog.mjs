#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { basename, dirname, join, posix, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const sourceRoot = resolve(root, '../model-resources/brown-dust-2')
const assetsRoot = join(sourceRoot, 'assets')
const report = JSON.parse(await readFile(join(sourceRoot, 'inventory-report.json'), 'utf8'))
const releaseRoot = join(root, 'release-assets/brown-dust-2')
const packageRoot = join(releaseRoot, 'packages')
await mkdir(packageRoot, { recursive: true })

const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'model'
const displayName = path => {
  const parts = path.split('/')
  if (parts[2] === 'character' && parts.length >= 5) return `${parts[3]} · ${parts[4].replaceAll('_', ' ')}`
  if (parts[2] === 'skill_cutscene' && parts.length >= 5) return `${parts[3]} · ${parts[4].replaceAll('_', ' ')} · 技能演出`
  if (parts[2]) return `${parts[2].replaceAll('_', ' ')} · ${basename(path, '.skel')}`
  return basename(path, '.skel')
}
const categoryFor = path => path.includes('/character/') ? 'character' : 'other'

const entries = []
const errors = []
for (const model of report.models) {
  const modelPath = model.path.replaceAll('\\', '/')
  const atlasPath = modelPath.replace(/\.skel$/i, '.atlas')
  const skelFile = join(sourceRoot, modelPath)
  const atlasFile = join(sourceRoot, atlasPath)
  try {
    const [skeleton, atlas] = await Promise.all([readFile(skelFile), readFile(atlasFile)])
    const id = `bd2-${createHash('sha1').update(modelPath).digest('hex').slice(0, 16)}`
    const packageSource = `(()=>{(globalThis.__MMD_SPINE_PACKAGES__??=Object.create(null))[${JSON.stringify(id)}]=${JSON.stringify({
      skeleton: `data:application/octet-stream;base64,${skeleton.toString('base64')}`,
      atlas: `data:text/plain;charset=utf-8;base64,${atlas.toString('base64')}`,
    })}})();\n`
    await writeFile(join(packageRoot, `${id}.js`), packageSource)
    const textureBytes = await Promise.all(model.textures.map(async texture => {
      try { return (await stat(join(sourceRoot, texture.path.replaceAll('\\', '/')))).size } catch { return 0 }
    }))
    const modelDir = posix.dirname(modelPath).replace(/^assets\//, '')
    const fileName = basename(modelPath)
    const atlasName = basename(atlasPath)
    const label = `${displayName(modelPath)} · ${fileName.replace(/\.skel$/i, '')}`
    const asset = {
      id, label, runtimeVersion: '4.1',
      basePath: `/_brown-model-files/${modelDir}/`, skeleton: fileName,
      skeletonType: 'binary', atlas: atlasName, externalScript: `/_brown-model-release/packages/${id}.js`,
      externalPackage: id, animation: model.animations.find(name => /^idle$/i.test(name)) ?? model.animations.find(name => /idle/i.test(name)) ?? model.animations[0],
      skin: model.skins.includes('default') ? 'default' : model.skins[0], loop: true, scale: 1,
      premultipliedAlpha: Boolean(model.textures[0]?.pma), source: 'local',
    }
    const estimatedBytes = Buffer.byteLength(packageSource) + textureBytes.reduce((sum, bytes) => sum + bytes, 0)
    entries.push({ id, name: displayName(modelPath), category: categoryFor(modelPath), estimatedBytes, asset,
      variants: [{ id, label, estimatedBytes, asset, animations: model.animations, skins: model.skins }] })
  } catch (error) {
    errors.push({ path: modelPath, error: error instanceof Error ? error.message : String(error) })
  }
}
entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))
const rows = entries.map(entry => ({ ...entry, thumbnail: undefined }))
await writeFile(join(root, 'src/renderers/spine/brownDustCatalog.generated.ts'),
  `import type { SpineCatalogEntry } from './spineTypes'\n// Generated by scripts/generate-brown-dust-catalog.mjs.\nexport const brownDustCatalogRows = ${JSON.stringify(rows)} as SpineCatalogEntry[]\n`)
await writeFile(join(releaseRoot, 'catalog.local.json'), JSON.stringify(rows))
await writeFile(join(releaseRoot, 'generation-report.json'), JSON.stringify({ generatedAt: new Date().toISOString(), source: report.repository, models: entries.length, errors }, null, 2))
console.log(JSON.stringify({ models: entries.length, errors, releaseRoot }, null, 2))
if (errors.length) process.exitCode = 1
