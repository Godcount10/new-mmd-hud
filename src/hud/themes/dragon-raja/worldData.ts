function spiritCategory(value: string): OpeningSpiritCategory {
  if (value.startsWith('常规 ·')) return '已觉醒·常规言灵'
  if (value.startsWith('危险 ·')) return '已觉醒·危险言灵'
  if (value.startsWith('精神 / 辅助 ·')) return '精神系/辅助系'
  return '未知'
}

export const OPENING_SPIRIT_OPTIONS: readonly OpeningSpiritOption[] = (spiritGroup?.options ?? []).map((entry, index) => {
  const category = spiritCategory(entry)
  const prefix = category === '已觉醒·常规言灵'
    ? '常规 · '
    : category === '已觉醒·危险言灵'
      ? '危险 · '
      : category === '精神系/辅助系'
        ? '精神 / 辅助 · '
        : '未知 · '
  const choice = splitChoice(entry.slice(prefix.length))
  return { id: `spirit-${index + 1}`, category, label: choice.label, description: choice.description }
})

